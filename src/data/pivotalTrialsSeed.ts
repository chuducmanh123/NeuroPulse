/**
 * Converts ConferenceEvent.lateBreakingTrials into PivotalTrialRecord items with CONFERENCE_LATE_BREAKING provenance
 * and merges them with the seed and dynamic pivotal trials without duplication.
 */
export function mergePivotalTrialsWithConferences(
  customTrials: PivotalTrialRecord[] = [],
  conferences: ConferenceEvent[] = []
): PivotalTrialRecord[] {
  const byKey = new Map<string, PivotalTrialRecord>();
  const normKey = (acr: string) => (acr || "").toLowerCase().replace(/[^a-z0-9]/g, "");

  for (const seed of PIVOTAL_TRIALS_SEED) {
    byKey.set(normKey(seed.acronym || seed.id), seed);
  }

  for (const conf of conferences) {
    for (const lbt of conf.lateBreakingTrials || []) {
      const k = normKey(lbt.trialAcronym || lbt.id);
      if (!k || byKey.has(k)) continue;
      const combinedText = `${lbt.title} ${lbt.populationSummary} ${lbt.interventionGroup}`.toLowerCase();
      const conds: string[] = [];
      if (combinedText.includes("ischemic") || combinedText.includes("ischaemic") || combinedText.includes("ais")) conds.push("ais");
      if (combinedText.includes("large vessel") || combinedText.includes("lvo")) conds.push("large_vessel_occlusion");
      if (combinedText.includes("mevo") || combinedText.includes("medium") || combinedText.includes("distal")) conds.push("medium_distal_vessel_occlusion");
      if (combinedText.includes("large core") || combinedText.includes("aspects")) conds.push("large_ischemic_core");
      if (combinedText.includes("intracerebral") || combinedText.includes("ich")) conds.push("ich");
      if (combinedText.includes("subarachnoid") || combinedText.includes("asah")) conds.push("sah");
      if (conds.length === 0 && lbt.subspecialty === "Stroke") conds.push("stroke_general");

      const drugs: string[] = [];
      if (combinedText.includes("tenecteplase") || combinedText.includes("tnk")) drugs.push("tenecteplase");
      if (combinedText.includes("alteplase") || combinedText.includes("tpa")) drugs.push("alteplase");
      if (combinedText.includes("thrombectomy") || combinedText.includes("evt")) drugs.push("mechanical_thrombectomy_device");

      byKey.set(k, {
        id: lbt.id,
        acronym: lbt.trialAcronym,
        title: lbt.title,
        year: conf.year || 2026,
        journal: lbt.publishedJournal || `${conf.acronym} ${conf.year} Late-Breaking`,
        officialUrl: lbt.fullTextUrl || conf.officialUrl,
        subspecialty: lbt.subspecialty,
        evidenceSource: "CONFERENCE_LATE_BREAKING",
        design: lbt.studyDesign,
        pico: {
          population: lbt.populationSummary,
          intervention: lbt.interventionGroup,
          comparator: lbt.controlGroup,
        },
        primaryEndpoint: {
          metric: "Primary Endpoint",
          resultStats: lbt.primaryOutcome,
          verdict: lbt.verdict,
        },
        safetyEndpoint: {
          note: lbt.safetyOutcome,
        },
        bottomLine: lbt.bottomLineTakeaway,
        ontologyTags: {
          condition: conds,
          drug_or_procedure: drugs,
          direction: [lbt.verdict === "POSITIVE" ? "for" : lbt.verdict === "NEGATIVE" ? "against" : "uncertain"],
        },
        linkedScenarioIds: lbt.impactedScenarioId ? [lbt.impactedScenarioId] : undefined,
      });
    }
  }

  for (const ct of customTrials) {
    if (!ct || !ct.acronym) continue;
    byKey.set(normKey(ct.acronym), ct);
  }

  return Array.from(byKey.values()).sort((a, b) => b.year - a.year || a.acronym.localeCompare(b.acronym));
}
